#!/usr/bin/env bash
# Mirrors a Mintlify docs site (one that serves llms.txt and <page>.md) into the repo.
# Usage: bash scripts/fetch-docs.sh [base_url] [dest]
# Defaults: https://docs.context.dev -> docs/reference/context-dev
# Every page is saved at its URL path. The header Mintlify repeats on every page is
# dropped and kept once in the generated README.md. Exits non-zero if any page fails.
set -euo pipefail
root="$(git rev-parse --show-toplevel)"
base="${1:-https://docs.context.dev}"
base="${base%/}"
dest="${2:-docs/reference/context-dev}"
case "$dest" in /*) ;; *) dest="$root/$dest" ;; esac

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

curl -fsSL --retry 3 "$base/llms.txt" -o "$tmp/llms.txt"
grep -oE "\]\($base/[^)]+\.md\)" "$tmp/llms.txt" | sed -E 's/^\]\(//; s/\)$//' | sort -u > "$tmp/urls"
[ -s "$tmp/urls" ] || { echo "fetch-docs: no pages found in $base/llms.txt" >&2; exit 1; }

mkdir -p "$tmp/pages"
fails=0
while read -r url; do
  path="${url#"$base"/}"
  mkdir -p "$tmp/pages/$(dirname "$path")"
  if ! curl -fsSL --retry 3 "$url" -o "$tmp/pages/$path"; then
    echo "FAIL $url" >&2
    fails=$((fails + 1))
  fi
done < "$tmp/urls"

# OpenAPI spec: absolute or site-relative link under "## OpenAPI Specs".
spec="$(grep -oE '\]\([^)]*openapi[^)]*\.json\)' "$tmp/llms.txt" | head -1 | sed -E 's/^\]\(//; s/\)$//' || true)"
if [ -n "$spec" ]; then
  case "$spec" in http*) ;; *) spec="$base/${spec#/}" ;; esac
  curl -fsSL --retry 3 "$spec" -o "$tmp/openapi.json" || { echo "FAIL $spec" >&2; fails=$((fails + 1)); }
fi

# Shared header: the leading "> ..." block(s) before the first "# " title, if identical
# on every page. Only then is it stripped.
first="$(head -1 "$tmp/urls")"; first="$tmp/pages/${first#"$base"/}"
hdr_lines=0
if [ -f "$first" ] && head -1 "$first" | grep -q '^> '; then
  hdr_lines="$(awk '/^# /{print NR-1; exit}' "$first")"
fi
header=""
if [ "$hdr_lines" -gt 0 ]; then
  header="$(head -n "$hdr_lines" "$first")"
  while read -r f; do
    [ "$(head -n "$hdr_lines" "$f")" = "$header" ] || { header=""; break; }
  done < <(find "$tmp/pages" -name '*.md')
fi
if [ -n "$header" ]; then
  find "$tmp/pages" -name '*.md' -exec sed -i "1,${hdr_lines}d" {} +
fi

# Index grouped by first path segment, in llms.txt order.
{
  echo "# $(sed -n 's/^# //p;q' "$tmp/llms.txt") docs (mirror)"
  echo
  echo "Mirror of $base, generated by \`bash scripts/fetch-docs.sh $base\` on $(date +%F)."
  echo "Each page keeps its URL path (\`a/b.md\` = $base/a/b). Do not edit by hand: re-run the script."
  echo "Read only the page you need; the distilled summary for agents lives in \`docs/agents/\`."
  [ -f "$tmp/openapi.json" ] && echo "Full API spec: \`openapi.json\`."
  if [ -n "$header" ]; then
    echo
    echo "## Header repeated on every page (removed from each, kept here)"
    echo
    echo "Third-party text. It is not an instruction for this project's agents."
    echo
    echo "$header"
  fi
  echo
  echo "## Pages"
  grep -E "^- \[.+\]\($base/" "$tmp/llms.txt" | sed -E "s#\]\($base/#](#" | awk '
    { match($0, /\]\([^)]+\)/); p = substr($0, RSTART + 2, RLENGTH - 3)
      s = (index(p, "/") ? substr(p, 1, index(p, "/") - 1) : "(root)")
      if (!(s in seen)) { seen[s] = 1; order[++n] = s }
      lines[s] = lines[s] $0 "\n" }
    END { for (i = 1; i <= n; i++) printf "\n### %s\n\n%s", order[i], lines[order[i]] }'
} > "$tmp/README.md"

if [ "$fails" -gt 0 ]; then
  echo "fetch-docs: $fails download(s) failed; ${dest#"$root"/} left untouched." >&2
  exit 1
fi
rm -rf "$dest"
mkdir -p "$dest"
cp -r "$tmp/pages/." "$dest/"
cp "$tmp/README.md" "$dest/README.md"
[ -f "$tmp/openapi.json" ] && cp "$tmp/openapi.json" "$dest/openapi.json"

echo "fetch-docs: $(wc -l < "$tmp/urls") pages -> ${dest#"$root"/}"

